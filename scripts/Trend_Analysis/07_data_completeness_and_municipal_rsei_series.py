# -*- coding: utf-8 -*-
"""
Data completeness per capital and municipality-level annual RSEI series.
New for Review (2026). Reads the annual RSEI assets generated by the original
pipeline and records (i) the years available per capital, (ii) the gap-filling
diagnostics stored as image properties by the original script, and (iii) the
annual municipal mean/median/SD of RSEI within the official IBGE municipal boundary. Output: out_S1_city_annual_series.csv
(used for Table S1, Table S2 and Figure S1 of the revised manuscript).
"""
import sys
import os
import csv
import ee
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'common'))
import gee_init_and_rsei_assets as C
import municipal_boundaries as MG

C.init()
col, ids = C.load_merged_collection()
muns = C.municipalities(col)
GEOMS = MG.ee_geometries()
print('images:', len(ids), 'municipalities:', len(muns), flush=True)

rows = []
for i, mun in enumerate(muns, 1):
    ic = col.filter(ee.Filter.eq('NM_MUN', mun)).sort('ANO')
    meta = ee.FeatureCollection(ic.map(lambda im: ee.Feature(None, {
        'ANO': im.get('ANO'), 'missing_before': im.get('RSEI_missing_before_fill'),
        'missing_after': im.get('RSEI_missing_after_fill'), 'gapfill_status': im.get('RSEI_gapfill_status'),
        'asset': im.get('system:id')}))).getInfo()['features']
    years = [int(f['properties']['ANO']) for f in meta]
    names = [f'y{y}' for y in years]
    stack = ic.select('RSEI').toBands().rename(names)
    red = (ee.Reducer.mean().combine(ee.Reducer.median(), sharedInputs=True)
           .combine(ee.Reducer.stdDev(), sharedInputs=True))
    d = stack.reduceRegion(reducer=red, geometry=GEOMS[mun], scale=30, maxPixels=1e13, tileScale=8).getInfo()
    for f, n in zip(meta, names):
        p = f['properties']
        rows.append({'NM_MUN': mun, 'ANO': int(p['ANO']), 'RSEI_mean': d.get(n + '_mean'),
                     'RSEI_median': d.get(n + '_median'), 'RSEI_stdDev': d.get(n + '_stdDev'),
                     'missing_before_fill': p.get('missing_before'), 'missing_after_fill': p.get('missing_after'),
                     'gapfill_status': p.get('gapfill_status'), 'asset': p.get('asset')})
    print(f'[{i}/{len(muns)}] {mun}: {len(meta)} years', flush=True)
    with open('out_S1_city_annual_series.csv', 'w', newline='', encoding='utf-8') as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
print('done', flush=True)
