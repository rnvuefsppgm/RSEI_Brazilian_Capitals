# HELPERS: numéricos seguros
# ============================================================
def safe_num(props_dict, name):
    v = props_dict.get(name)
    v = ee.Algorithms.If(v, v, 0)

    s = ee.String(v)
    is_numeric = s.match('^-?\\d+(\\.\\d+)?$')
    n = ee.Number(ee.Algorithms.If(is_numeric, ee.Number.parse(s), 0))

    return ee.Image.constant(n).rename(name)

