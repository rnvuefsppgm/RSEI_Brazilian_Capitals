def build_annual_rsei_image(year, feat):
    year = ee.Number(year)
    region = feat.geometry()

    start = ee.Date.fromYMD(year, 1, 1)
    end   = start.advance(1, 'year')

    annual = IC.filterDate(start, end).median()
    annual = annual.clip(region)

    annual = fill_thermal_gaps(annual, region, SCALE, TILE_SCALE)

    annual = add_indices(annual, year)

    nNDVI = min_max_norm(annual, 'NDVI', region, SCALE, invert=False, tile_scale=TILE_SCALE)
    nWET  = min_max_norm(annual, 'WET',  region, SCALE, invert=False, tile_scale=TILE_SCALE)
    nNDSI = min_max_norm(annual, 'NDSI', region, SCALE, invert=True,  tile_scale=TILE_SCALE)
    nLST  = min_max_norm(annual, 'LST',  region, SCALE, invert=True,  tile_scale=TILE_SCALE)

    stack = ee.Image.cat([nNDVI, nWET, nNDSI, nLST]).rename(
        ['n_NDVI', 'n_WET', 'n_NDSI', 'n_LST']
    )

    pcs = run_pca(stack, region, SCALE, tile_scale=TILE_SCALE)
    pc1 = pcs.select('PC1')
    #pc2 = pcs.select('PC2')
    #pc3 = pcs.select('PC3')

    rsei0 = ee.Image.constant(1).subtract(pc1).rename('RSEI0')

    stats = rsei0.reduceRegion(
        reducer=ee.Reducer.minMax(),
        geometry=region,
        scale=SCALE,
        maxPixels=1e13,
        bestEffort=True,
        tileScale=TILE_SCALE
    )

    mn = ee.Number(stats.get('RSEI0_min'))
    mx = ee.Number(stats.get('RSEI0_max'))
    eps = ee.Number(1e-6)

    # cálculo original mantido
    rsei = rsei0.subtract(mn).divide(mx.subtract(mn).add(eps)).rename('RSEI')

    rsei, rsei_missing_before, rsei_missing_after = fill_rsei_gaps_complete(
        rsei, region, SCALE, TILE_SCALE
    )

    out = ee.Image.cat([
        #annual.select(['NDVI', 'WET', 'NDSI', 'LST', 'IBI', 'SI']),
        #stack,
        pc1.rename('PC1'),
        #pc2.rename('PC2'),
        #pc3.rename('PC3'),
        rsei
    ])

    props = feat.toDictionary([
        'AREA_KM2', 'CD_MUN', 'COD', 'CODS',
        'FID_1', 'FID_12', 'NM_MUN', 'SIGLA_UF', 'Sum_AREA_K'
    ])

    num_bands = ee.Image.cat([
        ee.Image.constant(year).rename('ANO'),
        safe_num(props, 'AREA_KM2'),
        safe_num(props, 'Sum_AREA_K'),
        safe_num(props, 'CD_MUN'),
        safe_num(props, 'COD'),
        safe_num(props, 'CODS'),
        safe_num(props, 'FID_1'),
        safe_num(props, 'FID_12')
    ]).toFloat()

    out = out.addBands(num_bands)

    out = out.set({
        'ANO': year,
        'AREA_KM2': props.get('AREA_KM2'),
        'Sum_AREA_K': props.get('Sum_AREA_K'),
        'CD_MUN': props.get('CD_MUN'),
        'COD': props.get('COD'),
        'CODS': props.get('CODS'),
        'FID_1': props.get('FID_1'),
        'FID_12': props.get('FID_12'),
        'NM_MUN': props.get('NM_MUN'),
        'SIGLA_UF': props.get('SIGLA_UF'),
        'geom_name': props.get('NM_MUN'),
        'gapfill_thermal': 'focalMean_r1_r2_r4_meanFallback',
        'gapfill_rsei': 'focalMean_r1_r2_r4_r8_r16_r32_meanFallback',
        'RSEI_missing_before_fill': rsei_missing_before,
        'RSEI_missing_after_fill': rsei_missing_after,
        'RSEI_gapfill_status': ee.Algorithms.If(
            ee.Number(rsei_missing_after).eq(0),
            'OK_NO_GAPS',
            'WARNING_GAPS_REMAIN'
        )
    })

    return out

